# Map free-text dietary restrictions to allergens that MUST be excluded.
_RESTRICTION_TO_ALLERGENS = {
    "nut": {"peanut", "tree_nut"}, "peanut": {"peanut"}, "tree nut": {"tree_nut"},
    "gluten": {"wheat"}, "wheat": {"wheat"}, "celiac": {"wheat"}, "coeliac": {"wheat"},
    "dairy": {"milk"}, "milk": {"milk"}, "lactose": {"milk"},
    "egg": {"egg"}, "soy": {"soy"}, "fish": {"fish"}, "shellfish": {"shellfish"},
    "sesame": {"sesame"},
}
# Certifications we can verify from catalog data.
_CERT_WORDS = {"halal": "halal", "zabiha": "halal", "kosher": "kosher", "glatt": "kosher", "kashrut": "kosher"}
# Ingredient facts we can verify from catalog tags.
_AVOID_WORDS = {"pork": "pork", "beef": "beef", "alcohol": "alcohol", "dry": "alcohol", "sober": "alcohol"}
# Phrases that mean "nothing to check".
_EMPTY_PHRASES = frozenset({"none", "no", "n/a", "na", "nothing", "no restrictions", "no allergies",
                            "no dietary restrictions", "no dietary needs", "all good", "-"})
# Words in a THEME that imply a dietary need even when the dietary field is blank.
_THEME_DIET_WORDS = {
    "halal": "halal", "zabiha": "halal", "kosher": "kosher", "glatt": "kosher",
    "vegan": "vegan", "plant-based": "vegan", "plant based": "vegan",
    "vegetarian": "vegetarian", "pure veg": "vegetarian", "jain": "vegetarian", "sattvic": "vegetarian",
    "gluten free": "gluten free", "gluten-free": "gluten free", "nut free": "nut free", "nut-free": "nut free",
}
# Needs we can name but cannot yet verify (no macro/ingredient data in catalog).
_UNVERIFIABLE_TOKENS = ("pescatarian", "keto", "paleo", "low carb", "low-carb", "diabetic", "fodmap", "whole30")


def _norm(text: str) -> str:
    return (text or "").lower().replace("-", " ").strip()


def _word_in(word: str, text: str) -> bool:
    import re
    return re.search(r"(?<![a-z0-9])" + re.escape(word) + r"(?![a-z0-9])", text) is not None


def parse_forbidden_allergens(restrictions: str) -> set[str]:
    text = (restrictions or "").lower()
    forbidden: set[str] = set()
    for key, allergens in _RESTRICTION_TO_ALLERGENS.items():
        if key in text:  # substring on purpose: 'nuts', 'peanuts', 'eggs', 'shellfish allergy' all count
            forbidden |= allergens
    # Vegan excludes all animal-derived allergen categories we track. (Within
    # this catalog's taxonomy that is milk, egg, fish, shellfish; honey/gelatin
    # would need explicit item flags in a richer catalog.)
    if "vegan" in text or "plant based" in text.replace("-", " "):
        forbidden |= {"milk", "egg", "fish", "shellfish"}
    return forbidden


def requires_vegetarian(restrictions: str) -> bool:
    text = _norm(restrictions)
    return "vegetarian" in text or "vegan" in text or "plant based" in text or "pure veg" in text or "jain" in text


def certification_needs(restrictions: str) -> set[str]:
    text = _norm(restrictions)
    return {cert for word, cert in _CERT_WORDS.items() if _word_in(word, text)}


def avoid_needs(restrictions: str) -> set[str]:
    """'no pork', 'pork-free', 'alcohol-free' -> ingredient tags to keep off the menu."""
    text = _norm(restrictions)
    out: set[str] = set()
    for word, tag in _AVOID_WORDS.items():
        if word == "dry":
            if "dry party" in text or "dry event" in text or "dry wedding" in text:
                out.add(tag)
        elif _word_in(word, text):
            out.add(tag)
    if "halal" in text or "zabiha" in text:
        out |= {"pork", "alcohol"}
    if "kosher" in text or "glatt" in text:
        out.add("pork")
    return out


def split_pieces(text: str) -> list[str]:
    pieces = [p.strip() for p in (text or "").replace("\n", ";").replace(",", ";").split(";") if p.strip()]
    return [p for p in pieces if _norm(p) not in _EMPTY_PHRASES]


def _understood(piece: str) -> bool:
    return bool(parse_forbidden_allergens(piece) or requires_vegetarian(piece)
                or certification_needs(piece) or avoid_needs(piece))


def unverifiable_dietary(restrictions: str) -> str | None:
    """Return the first dietary need we do NOT understand or cannot verify — so
    the app can fail closed instead of silently shipping a plan that appears
    'checked'. Returns None when the need is empty, or fully handled (allergen,
    vegetarian, certification or ingredient).

    Compound needs are judged piece by piece ('gluten free; keto' -> 'keto'):
    a need we do understand must never let one we don't hide behind it."""
    for piece in split_pieces(restrictions):
        if _understood(piece):
            continue
        return piece
    return None


def theme_dietary_words(theme: str) -> list[str]:
    """Dietary needs a theme states outright ('Halal Engagement', 'Vegan Brunch')."""
    text = _norm(theme)
    found: list[str] = []
    for word, need in _THEME_DIET_WORDS.items():
        if _word_in(word.replace("-", " "), text) and need not in found:
            found.append(need)
    return found


@dataclass(frozen=True)
class DietContext:
    """Everything the engine knows about what must (not) be on the menu."""
    forbidden: frozenset[str] = frozenset()          # allergens
    vegetarian: bool = False
    vegan: bool = False
    certifications: frozenset[str] = frozenset()     # required: halal / kosher
    avoid: frozenset[str] = frozenset()              # ingredient tags: pork / beef / alcohol
    unverifiable: tuple[str, ...] = ()
    text: str = ""                                   # merged (dietary field + theme-lifted)

    @property
    def any(self) -> bool:
        return bool(self.forbidden or self.vegetarian or self.certifications or self.avoid)

    def safe(self, item: CatalogItem) -> bool:
        """Can this food item be served to everyone the context describes?"""
        if item.category != "food":
            return True
        if self.forbidden & item.allergens:
            return False
        if self.vegetarian and not item.vegetarian:
            return False
        for tag in self.avoid:
            if f"contains:{tag}" in item.tags:
                return False
        if "halal" in self.certifications and not item.vegetarian and "halal" not in item.certifications:
            return False
        return not ("kosher" in self.certifications and item.course != "drink" and "kosher" not in item.certifications)

    def venue_ok(self, item: CatalogItem) -> bool:
        """A venue package that includes the meal must meet the same bar."""
        if item.category != "venue" or "includes:main" not in item.tags:
            return True
        if self.forbidden & item.allergens:
            return False
        if self.vegetarian and not item.vegetarian:
            return False
        for tag in self.avoid:
            if f"contains:{tag}" in item.tags:
                return False
        if "halal" in self.certifications and not item.vegetarian and "halal" not in item.certifications:
            return False
        return not ("kosher" in self.certifications and "kosher" not in item.certifications)


def dietary_context(request) -> DietContext:
    """The dietary picture for a request: the dietary field plus any need the
    theme states outright. 'Halal Engagement' with a blank dietary field still
    gets certified halal food — that is what the host asked for."""
    base = request.dietary_restrictions or ""
    lifted = [w for w in theme_dietary_words(getattr(request, "theme", "") or "") if w not in _norm(base)]
    merged = "; ".join([p for p in [base.strip(), *lifted] if p])
    return DietContext(
        forbidden=frozenset(parse_forbidden_allergens(merged)),
        vegetarian=requires_vegetarian(merged),
        vegan=("vegan" in _norm(merged) or "plant based" in _norm(merged)),
        certifications=frozenset(certification_needs(merged)),
        avoid=frozenset(avoid_needs(merged)),
        unverifiable=tuple(p for p in split_pieces(merged) if not _understood(p)),
        text=merged,
    )
