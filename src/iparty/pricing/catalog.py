"""Grounded pricing + allergen catalog — the source of truth for realizability.

The core fix to the "hallucinated prices" problem: the language model never sets
prices. It *selects* catalog SKUs; the system prices them from this catalog. A
plan is therefore "budget-valid" only if it is **buyable** from real, priced
inventory. Swap `StaticCatalog` for a live vendor/pricing API behind the same
`Catalog` protocol and nothing else changes.

Catalog v2 (src/iparty/pricing/data/catalog_v2.json, generated by
scripts/build_catalog.py) covers every segment — toddlers to galas — and every
item carries the facts the engine reasons about: a course, a tier, segment /
cuisine / theme / mood tags, ingredient facts (contains:pork), certifications
(halal, kosher), capacity and billing minimums, and lead times. Prices are
representative US market rates for 2026; allergen data uses the FDA big-9.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path
from typing import Literal, Protocol

Category = Literal["venue", "food", "supplies", "activities"]

# FDA big-9 allergens
ALLERGENS = frozenset(
    {"milk", "egg", "peanut", "tree_nut", "soy", "wheat", "fish", "shellfish", "sesame"}
)
COURSES = ("main", "side", "snack", "dessert", "cake", "drink")
TIERS = ("essential", "standard", "premium", "luxury")
DATA_DIR = Path(__file__).resolve().parent / "data"
CATALOG_V2 = DATA_DIR / "catalog_v2.json"

# Old SKU -> current SKU, so saved Living Passes and external integrations
# written against earlier catalogs keep resolving.
LEGACY_SKUS: dict[str, str] = {
    "SUP-TABLE-PACK16": "SUP-BASIC",
    "SUP-TABLE-PACK24-THEMED": "SUP-DELUXE",
    "ACT-GAME": "ACT-GAMES",
    "VEN-KIDS-VENUE": "VEN-KIDS",
}

_ALL_LOCATIONS = frozenset({"home", "venue", "park", "restaurant"})


@dataclass(frozen=True)
class CatalogItem:
    sku: str
    category: Category
    name: str
    unit: Literal["per_person", "flat", "per_hour", "each"]
    unit_price: float
    serves: int = 0                      # servings per unit (food) / settings per pack (tableware)
    allergens: frozenset[str] = field(default_factory=frozenset)
    vegetarian: bool = True
    min_age: int = 0
    max_age: int = 120
    location_types: frozenset[str] = field(default_factory=lambda: _ALL_LOCATIONS)
    # ---- v2 facts ----
    subcategory: str = ""                # food: a course; venue/supplies/activities: a kind
    description: str = ""
    tier: str = "standard"
    tags: frozenset[str] = field(default_factory=frozenset)
    certifications: frozenset[str] = field(default_factory=frozenset)
    min_guests: int = 1                  # billing floor for per_person items
    max_guests: int = 500                # capacity
    lead_days: int = 0
    price_basis: str = "catalog"
    sources: tuple[str, ...] = ()

    # ---- facts ----
    @property
    def course(self) -> str:
        return self.subcategory if self.category == "food" else ""

    def has(self, tag: str) -> bool:
        return tag in self.tags

    @property
    def is_tableware(self) -> bool:
        return self.category == "supplies" and (self.subcategory == "tableware" or (not self.subcategory and (self.serves > 0 or self.unit == "per_person")))

    @property
    def is_service(self) -> bool:
        """Staffing, planning and transport are bought like activities but are
        not entertainment — they never satisfy 'at least one activity'."""
        return self.category == "activities" and self.subcategory in {"staffing", "planning", "transport", "ceremony"}

    # ---- money & portions ----
    def billable_guests(self, guests: int) -> int:
        """Caterers bill a minimum head count; below it you pay the floor."""
        return max(guests, self.min_guests) if self.unit == "per_person" else guests

    def price_for(self, quantity: int, guests: int) -> float:
        if self.unit == "per_person":
            return round(self.unit_price * self.billable_guests(guests), 2)
        return round(self.unit_price * quantity, 2)

    def servings_for(self, quantity: int, guests: int) -> int:
        if self.category != "food":
            return 0
        if self.unit == "per_person":
            return guests * max(1, self.serves or 1)
        return self.serves * quantity

    def settings_for(self, quantity: int, guests: int) -> int:
        """Place settings a tableware line provides."""
        if not self.is_tableware:
            return 0
        return guests if self.unit == "per_person" else self.serves * quantity

    def within_capacity(self, guests: int) -> bool:
        return guests <= self.max_guests

    def below_minimum(self, guests: int) -> bool:
        return guests < self.min_guests

    def fits_guests(self, guests: int) -> bool:
        return self.within_capacity(guests)


class Catalog(Protocol):
    def all(self) -> list[CatalogItem]: ...
    def get(self, sku: str) -> CatalogItem | None: ...
    def by_category(self, category: Category) -> list[CatalogItem]: ...


def item_from_dict(row: dict) -> CatalogItem:
    allergens = frozenset(row.get("allergens") or ())
    unknown = allergens - ALLERGENS
    if unknown:
        raise ValueError(f"SKU {row.get('sku')}: unknown allergen keys {sorted(unknown)}")
    return CatalogItem(
        sku=row["sku"], category=row["category"], name=row["name"], unit=row["unit"],
        unit_price=float(row["unit_price"]), serves=int(row.get("serves") or 0),
        allergens=allergens, vegetarian=bool(row.get("vegetarian", True)),
        min_age=int(row.get("min_age") or 0), max_age=int(row.get("max_age", 120)),
        location_types=frozenset(row.get("location_types") or _ALL_LOCATIONS),
        subcategory=row.get("subcategory", ""), description=row.get("description", ""),
        tier=row.get("tier", "standard"), tags=frozenset(row.get("tags") or ()),
        certifications=frozenset(row.get("certifications") or ()),
        min_guests=int(row.get("min_guests") or 1), max_guests=int(row.get("max_guests") or 500),
        lead_days=int(row.get("lead_days") or 0), price_basis=row.get("price_basis", "catalog"),
        sources=tuple(row.get("sources") or ()),
    )


@lru_cache(maxsize=1)
def load_catalog_v2() -> tuple[CatalogItem, ...]:
    doc = json.loads(CATALOG_V2.read_text(encoding="utf-8"))
    return tuple(item_from_dict(r) for r in doc["items"])


class StaticCatalog:
    """Default in-repo catalog (v2). Replace with a live vendor API behind `Catalog`."""

    def __init__(self, items: list[CatalogItem] | None = None) -> None:
        self._items = list(items) if items is not None else list(load_catalog_v2())
        self._by_sku = {i.sku: i for i in self._items}

    def all(self) -> list[CatalogItem]:
        return list(self._items)

    def get(self, sku: str) -> CatalogItem | None:
        item = self._by_sku.get(sku)
        if item is None and sku in LEGACY_SKUS:
            item = self._by_sku.get(LEGACY_SKUS[sku])
        return item

    def by_category(self, category: Category) -> list[CatalogItem]:
        return [i for i in self._items if i.category == category]

    @classmethod
    def with_vendors(cls, path: str | Path | None = None) -> StaticCatalog:
        """The static catalog plus approved vendor rows (data/vendor_catalog.jsonl
        by default). Vendor SKUs override static ones with the same code."""
        from .vendors import load_vendor_items  # local import: vendors imports this module

        base = {i.sku: i for i in load_catalog_v2()}
        for item in load_vendor_items(path):
            base[item.sku] = item
        return cls(list(base.values()))


def load_catalog_csv(path: str | Path) -> StaticCatalog:
    """Vendor onboarding without code: build a catalog from a CSV.

    Columns: sku,category,name,unit,unit_price,serves,allergens,vegetarian,
             min_age,max_age,location_types
             [optional: subcategory,tier,tags,certifications,min_guests,max_guests,lead_days,description]
    allergens: semicolon-separated FDA big-9 keys (blank = none)
    location_types / tags / certifications: semicolon-separated (blank = all / none)
    Unknown allergen keys raise immediately — a typo in safety data must fail
    loudly at load time, never silently at verify time.
    """
    import csv
    from pathlib import Path as _Path

    items: list[CatalogItem] = []
    with _Path(path).open(newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            allergens = frozenset(a.strip() for a in (row.get("allergens") or "").split(";") if a.strip())
            unknown = allergens - ALLERGENS
            if unknown:
                raise ValueError(f"SKU {row['sku']}: unknown allergen keys {sorted(unknown)}; "
                                 f"allowed: {sorted(ALLERGENS)}")
            def split(key: str, row: dict = row) -> frozenset[str]:
                return frozenset(x.strip() for x in (row.get(key) or "").split(";") if x.strip())
            locs = split("location_types")
            items.append(CatalogItem(
                sku=row["sku"].strip(), category=row["category"].strip(),  # type: ignore[arg-type]
                name=row["name"].strip(), unit=row["unit"].strip(),        # type: ignore[arg-type]
                unit_price=float(row["unit_price"]),
                serves=int(row.get("serves") or 0),
                allergens=allergens,
                vegetarian=((row.get("vegetarian") or "true").strip().lower() != "false"),
                min_age=int(row.get("min_age") or 0),
                max_age=int(row.get("max_age") or 120),
                location_types=locs or _ALL_LOCATIONS,
                subcategory=(row.get("subcategory") or "").strip(),
                tier=(row.get("tier") or "standard").strip(),
                tags=split("tags"), certifications=split("certifications"),
                min_guests=int(row.get("min_guests") or 1), max_guests=int(row.get("max_guests") or 500),
                lead_days=int(row.get("lead_days") or 0), description=(row.get("description") or "").strip(),
                price_basis="vendor",
            ))
    if not items:
        raise ValueError(f"catalog CSV {path} contained no items")
    return StaticCatalog(items)


